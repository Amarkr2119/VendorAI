"""Process all synthetic applications through the full pipeline and compare decisions with data/synthetic/manifest.csv.

    python scripts/evaluate_decisions.py [--mode DEMO|PRODUCTION] [--out docs/PHASE4_DECISION_EVALUATION.md]

Uses a throw-away database. Verification is SIMULATED (fixtures); no external API is called.
"""
from __future__ import annotations

import argparse
import csv
import logging
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vendorflow.config import Settings  # noqa: E402
from vendorflow.services import build_services, register_synthetic, synthetic_index  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="DEMO", choices=["DEMO", "PRODUCTION"])
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    logging.disable(logging.CRITICAL)
    tmp = Path(tempfile.mkdtemp(prefix="vf_eval_"))
    svc = build_services(Settings(db_path=tmp / "e.db", upload_dir=tmp / "u", log_file=None, llm_enabled=False, app_mode=a.mode, verify_backoff_s=0.0))
    man = {r["ref"]: r for r in csv.DictReader(open(Path(__file__).resolve().parents[1] / "data/synthetic/manifest.csv"))}
    col = "expected_auto_decision_demo" if a.mode == "DEMO" else "expected_production_decision"
    lines = [f"| Ref | Scenario | Expected | Actual | Reason codes | Match |", "|---|---|---|---|---|---|"]
    ok = status_ok = 0
    counts = {}
    for entry in synthetic_index():
        ref = entry["ref"]
        app = register_synthetic(svc, ref)
        svc.pipeline.run_all(app)
        d = svc.repo.current_decision(app)
        exp = man[ref][col].split()[0].upper()
        codes = set(filter(None, man[ref]["expected_reason_codes"].split(";")))
        good_status = d["status"] == exp
        good = good_status and (codes <= set(d["reason_codes"]) if a.mode == "DEMO" else True)
        ok += good
        status_ok += good_status
        counts[d["status"]] = counts.get(d["status"], 0) + 1
        lines.append(f"| {ref} | {entry['scenario'][:60]} | {exp} | {d['status']} | {', '.join(d['reason_codes']) or '-'} | {'yes' if good else 'NO'} |")
    head = [f"# Phase 4 decision evaluation ({a.mode} mode)", "",
            f"Generated by `scripts/evaluate_decisions.py`. Verification: SIMULATED fixtures, no external API.", "",
            f"- Applications: {len(lines) - 2}", f"- Decision status matches manifest: {status_ok}", f"- Status AND expected reason codes match: {ok}",
            f"- Outcome distribution: {counts}", ""]
    text = "\n".join(head + lines) + "\n"
    print(text)
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
    return 0 if ok == len(lines) - 2 or a.mode == "PRODUCTION" else 1


if __name__ == "__main__":
    raise SystemExit(main())
